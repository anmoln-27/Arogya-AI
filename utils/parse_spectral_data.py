def parse_and_save():
    # Make directory
    target_dir = os.path.join("Arogya AI_EdgeImpulse", "Multi_Sensor_TS", "Anemia_Healthy")
    os.makedirs(target_dir, exist_ok=True)
    
    output_file = os.path.join(target_dir, "spectral_healthy.csv")
    
    lines = raw_log.strip().split('\n')
    
    # We will save two separate files or interleave them with headers
    # Edge Impulse likes CSVs with a header. Since SPEC and PULSE have different lengths,
    # we'll pad them into a unified table: Type, Timestamp, V1, V2, V3, V4, V5, V6, V7, V8, V9
    header = ["Sequence", "Type", "Val1", "Val2", "Val3", "Val4", "Val5", "Val6", "Val7", "Val8", "Val9"]
    
    with open(output_file, mode='w', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(header)
        
        for idx, line in enumerate(lines):
            parts = line.split(',')
            label = parts[0]
            values = parts[1:]
            
            # Pad to 9 columns
            padded = values + [""] * (9 - len(values))
            writer.writerow([idx, label] + padded)
            
    print(f"[OK] Healthy Spectral Data parsed and saved to {output_file}")

if __name__ == "__main__":
    parse_and_save()
